import { Router } from "express";
import rateLimit from "express-rate-limit";
import { register, login, logout, me } from "../controllers/authController.js";
import { listProblems, getProblem, createProblem, updateProblem, deleteProblem } from "../controllers/problemController.js";
import { runCode, submitCode, mySubmissions } from "../controllers/submissionController.js";
import { assist } from "../controllers/aiController.js";
import { myAnalytics } from "../controllers/analyticsController.js";
import { publicProfile } from "../controllers/profileController.js";
import { protect, adminOnly } from "../middleware/auth.js";
const router = Router();
const authLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false });
router.get("/health", (req,res) => res.json({ status: "ok", service: "CodeArena API" }));
router.post("/auth/register", authLimiter, register);
router.post("/auth/login", authLimiter, login);
router.post("/auth/logout", logout);
router.get("/auth/me", protect, me);
router.get("/problems", (req,res,next) => { if (req.cookies?.token) return protect(req,res,()=>listProblems(req,res)); return listProblems(req,res); });
router.get("/problems/:slug", getProblem);
router.post("/problems", protect, adminOnly, createProblem);
router.patch("/problems/:id", protect, adminOnly, updateProblem);
router.delete("/problems/:id", protect, adminOnly, deleteProblem);
router.post("/submissions/run", protect, runCode);
router.post("/submissions/submit", protect, submitCode);
router.get("/submissions/me", protect, mySubmissions);
router.post("/ai/assist", protect, assist);
router.get("/analytics/me", protect, myAnalytics);
router.get("/users/:username", publicProfile);
export default router;
